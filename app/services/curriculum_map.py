CORRECT_TO_FILL = 3
NEARLY_FULL = 0.92


MASTERED, LEARNING, OPEN, LOCKED, SOON = "mastered", "learning", "open", "locked", "soon"


def lesson_key(unit: Unit, lesson: Lesson) -> str:
    return f"u{unit.no}l{lesson.no}"


def all_lessons() -> list[tuple[Unit, Lesson]]:
    return [(u, l) for u in UNITS for l in u.lessons]


def find_by_skill(skill_id: str) -> Optional[tuple[Unit, Lesson]]:
    for u, l in all_lessons():
        if l.skill == skill_id:
            return u, l
    return None


def find_by_key(key: str) -> Optional[tuple[Unit, Lesson]]:
    for u, l in all_lessons():
        if lesson_key(u, l) == key:
            return u, l
    return None


def status(state, lesson: Lesson) -> str:
    sk = lesson.skill
    if not sk or sk not in kg.SKILLS:
        return SOON
    if state.is_mastered(sk):
        return MASTERED
    if state.attempts.get(sk, 0) > 0:
        return LEARNING
    if all(state.is_mastered(p) for p in kg.prerequisites(sk)):
        return OPEN
    return LOCKED


def progress(state, lesson: Lesson) -> float:
    st = status(state, lesson)
    if st == MASTERED:
        return 1.0
    if st != LEARNING:
        return 0.0
    correct = state.correct.get(lesson.skill, 0)
    return max(0.06, min(NEARLY_FULL, min(correct, CORRECT_TO_FILL) / CORRECT_TO_FILL))


def is_current(state, lesson: Lesson) -> bool:
    return bool(lesson.skill) and state.current_skill == lesson.skill


def missing_prerequisites(state, lesson: Lesson) -> list[str]:
    if not lesson.skill or lesson.skill not in kg.SKILLS:
        return []
    return [kg.SKILLS[p].name_ar for p in kg.prerequisites(lesson.skill) if not state.is_mastered(p)]


def summary(state) -> dict:
    lessons = all_lessons()
    mastered = sum(1 for _, l in lessons if status(state, l) == MASTERED)
    live = sum(1 for _, l in lessons if l.skill in kg.SKILLS)
    answered = sum(state.attempts.values())
    correct = sum(state.correct.values())
    return {"total": len(lessons), "live": live, "mastered": mastered,
            "answered": answered, "correct": correct}


