import re as _re

_MATH = _re.compile(r"\[\[(.+?)\]\]")


def segments(text: str) -> list[dict]:
    out = []
    pos = 0
    for found in _MATH.finditer(text):
        if found.start() > pos:
            out.append({"t": text[pos:found.start()], "m": False})
        out.append({"t": found.group(1), "m": True})
        pos = found.end()
    if pos < len(text):
        out.append({"t": text[pos:], "m": False})
    return out


def plain(text: str) -> str:
    return _MATH.sub(lambda found: found.group(1), text)
